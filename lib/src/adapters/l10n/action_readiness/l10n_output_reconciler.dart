bool _sameStrings(Iterable<String> left, Iterable<String> right) {
  final leftSet = left.toSet();
  final rightSet = right.toSet();
  return leftSet.length == rightSet.length && leftSet.containsAll(rightSet);
}

void _validateMode(int? value, String name) {
  if (value != null && (value < 0 || value > 0xfff)) {
    throw ArgumentError.value(value, name);
  }
}

bool _isSafeRelativePosixPath(String value) {
  if (value.isEmpty ||
      value.startsWith('/') ||
      value.endsWith('/') ||
      value.contains('\\') ||
      value.contains(':') ||
      value.contains('%') ||
      value.contains('?') ||
      value.contains('#') ||
      value.codeUnits.any((unit) => unit < 0x20 || unit > 0x7e)) {
    return false;
  }
  return value
      .split('/')
      .every(
        (segment) =>
            segment.isNotEmpty &&
            segment != '.' &&
            segment != '..' &&
            RegExp(r'^[A-Za-z0-9._-]+$').hasMatch(segment),
      );
}

String _asciiFold(String value) => String.fromCharCodes(
  value.codeUnits.map(
    (unit) => unit >= 0x41 && unit <= 0x5a ? unit + 0x20 : unit,
  ),
);
