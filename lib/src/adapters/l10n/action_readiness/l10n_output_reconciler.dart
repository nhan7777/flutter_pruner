bool _entryMatchesBytes(
  L10nStageEntry? entry,
  ImmutableBytes expected,
  int? expectedMode,
) =>
    entry != null &&
    entry.kind == L10nStageEntryKind.regularFile &&
    entry.sha256 == expected.sha256Hex &&
    entry.posixMode == expectedMode;

bool _entryMatchesCapturedBytes(
  L10nStageEntry? entry,
  ImmutableBytes expected,
  int? expectedMode,
) =>
    _entryMatchesBytes(entry, expected, expectedMode) &&
    _authoritativeCapturedBytes(entry!)?.contentEquals(expected) == true;

ImmutableBytes? _authoritativeCapturedBytes(L10nStageEntry entry) {
  if (entry.kind != L10nStageEntryKind.regularFile ||
      entry.sha256 == null ||
      entry.capturedBytes == null ||
      entry.capturedBytes!.sha256Hex != entry.sha256) {
    return null;
  }
  return ImmutableBytes.copyOf(entry.capturedBytes!.copy());
}

bool _sameEntry(L10nStageEntry? left, L10nStageEntry? right) =>
    identical(left, right) ||
    (left != null &&
        right != null &&
        left.kind == right.kind &&
        left.sha256 == right.sha256 &&
        left.posixMode == right.posixMode);

Iterable<String> _parentsOf(String path) sync* {
  final segments = path.split('/');
  for (var length = 1; length < segments.length; length++) {
    yield segments.take(length).join('/');
  }
}

Map<String, L10nFileReplacement> _copyReplacementMap(
  Map<String, L10nFileReplacement> source, {
  required String name,
}) {
  final result = SplayTreeMap<String, L10nFileReplacement>();
  final folded = <String, String>{};
  for (final entry in source.entries) {
    if (entry.key != entry.value.relativePath ||
        !_isSafeRelativePosixPath(entry.key)) {
      throw ArgumentError('$name contains a key/path mismatch.');
    }
    final previous = folded[_asciiFold(entry.key)];
    if (previous != null && previous != entry.key) {
      throw ArgumentError('$name contains a case-fold collision.');
    }
    folded[_asciiFold(entry.key)] = entry.key;
    final replacement = entry.value;
    result[entry.key] = L10nFileReplacement(
      relativePath: replacement.relativePath,
      beforeBytes: replacement.beforeBytes,
      afterBytes: replacement.afterBytes,
      beforeMode: replacement.beforeMode,
      afterMode: replacement.afterMode,
    );
  }
  return UnmodifiableMapView(result);
}

String _changeSetFingerprint(
  Map<String, L10nFileReplacement> arbs,
  Map<String, L10nFileReplacement> generated,
) {
  final writer = _FingerprintWriter()..addString(_fingerprintSchema);
  void addMap(String role, Map<String, L10nFileReplacement> replacements) {
    writer
      ..addString(role)
      ..addInt(replacements.length);
    for (final replacement in replacements.values) {
      writer
        ..addString(replacement.relativePath)
        ..addInt(replacement.beforeBytes.length)
        ..addString(replacement.beforeBytes.sha256Hex)
        ..addNullableInt(replacement.beforeMode)
        ..addInt(replacement.afterBytes.length)
        ..addString(replacement.afterBytes.sha256Hex)
        ..addNullableInt(replacement.afterMode);
    }
  }

  addMap('arb', arbs);
  addMap('generated', generated);
  return writer.finish();
}

final class _FingerprintWriter {
  final BytesBuilder _bytes = BytesBuilder(copy: false);

  void addString(String value) {
    final encoded = utf8.encode(value);
    addInt(encoded.length);
    _bytes.add(encoded);
  }

  void addInt(int value) => addStringWithoutLength(value.toString());

  void addNullableInt(int? value) =>
      addStringWithoutLength(value?.toString() ?? 'null');

  void addStringWithoutLength(String value) {
    final encoded = utf8.encode(value);
    final length = ByteData(8)..setUint64(0, encoded.length);
    _bytes
      ..add(length.buffer.asUint8List())
      ..add(encoded);
  }

  String finish() => sha256.convert(_bytes.takeBytes()).toString();
}

Set<String> _sortedPathSet(
  Iterable<String> source, {
  required String name,
  bool requireNonEmpty = false,
}) {
  final result = SplayTreeSet<String>();
  final folded = <String, String>{};
  for (final path in source) {
    if (!_isSafeRelativePosixPath(path)) {
      throw ArgumentError.value(path, name);
    }
    final previous = folded[_asciiFold(path)];
    if (previous != null && previous != path) {
      throw ArgumentError('$name contains a case-fold collision.');
    }
    folded[_asciiFold(path)] = path;
    result.add(path);
  }
  if (requireNonEmpty && result.isEmpty) {
    throw ArgumentError('$name must not be empty.');
  }
  return Set<String>.unmodifiable(result);
}

void _validateNonAliasingPaths(Iterable<String> paths, String name) {
  final folded = paths.map(_asciiFold).toSet().toList()..sort();
  if (folded.length != paths.length) {
    throw ArgumentError('$name contains a case-fold collision.');
  }
  for (var index = 0; index < folded.length; index++) {
    final ancestor = folded[index];
    for (var other = index + 1; other < folded.length; other++) {
      final candidate = folded[other];
      if (candidate.startsWith('$ancestor/')) {
        throw ArgumentError('$name contains an ancestor/leaf alias.');
      }
    }
  }
}

List<L10nEvidenceFailure> _sortedFailures(
  Iterable<L10nEvidenceFailure> source,
) {
  final ordered = source.toList(growable: false)..sort(_compareFailures);
  final deduplicated = <L10nEvidenceFailure>[];
  for (final failure in ordered) {
    if (deduplicated.isEmpty ||
        _compareFailures(deduplicated.last, failure) != 0) {
      deduplicated.add(failure);
    }
  }
  return List<L10nEvidenceFailure>.unmodifiable(deduplicated);
}

int _compareFailures(L10nEvidenceFailure left, L10nEvidenceFailure right) {
  var comparison = left.code.index.compareTo(right.code.index);
  if (comparison != 0) return comparison;
  comparison = left.stage.compareTo(right.stage);
  if (comparison != 0) return comparison;
  comparison = _compareNullable(left.relativePath, right.relativePath);
  if (comparison != 0) return comparison;
  return left.detailCode.compareTo(right.detailCode);
}

int _compareNullable(String? left, String? right) {
  if (left == null) return right == null ? 0 : -1;
  if (right == null) return 1;
  return left.compareTo(right);
}

